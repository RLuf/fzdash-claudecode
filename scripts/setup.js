#!/usr/bin/env node

/**
 * FZDash-ClaudeCode Interactive Setup
 * Configures the dashboard for first use
 */

import { execSync } from 'child_process';
import { existsSync, readFileSync, writeFileSync } from 'fs';
import { join } from 'path';
import inquirer from 'inquirer';
import chalk from 'chalk';
import ora from 'ora';

const PROJECT_ROOT = join(import.meta.dirname || __dirname, '..');
const ENV_FILE = join(PROJECT_ROOT, '.env');
const ENV_EXAMPLE = join(PROJECT_ROOT, '.env.example');

function checkDependencies() {
  const spinner = ora('Checking dependencies...').start();

  try {
    // Check Node version
    const nodeVersion = process.version;
    const majorVersion = parseInt(nodeVersion.split('.')[0].substring(1));

    if (majorVersion < 18) {
      spinner.fail(`Node.js ${nodeVersion} found, but version 18+ required`);
      console.log(chalk.yellow('\nPlease upgrade Node.js to version 18 or higher'));
      process.exit(1);
    }

    spinner.succeed(`Node.js ${nodeVersion} ✓`);
  } catch (error) {
    spinner.fail('Failed to check dependencies');
    throw error;
  }
}

function checkQdrant() {
  const spinner = ora('Checking Qdrant connection...').start();

  try {
    const response = execSync('curl -s http://localhost:6363/collections', {
      encoding: 'utf-8',
      timeout: 5000
    });

    const data = JSON.parse(response);

    if (data.status === 'ok') {
      spinner.succeed('Qdrant connected ✓');
      return true;
    } else {
      spinner.warn('Qdrant returned unexpected response');
      return false;
    }
  } catch (error) {
    spinner.warn('Qdrant not accessible on localhost:6363');
    return false;
  }
}

function checkClaudeCode() {
  const spinner = ora('Checking Claude Code...').start();

  try {
    execSync('claude --version', { stdio: 'pipe' });
    spinner.succeed('Claude Code installed ✓');
    return true;
  } catch {
    spinner.warn('Claude Code not found in PATH');
    return false;
  }
}

async function promptConfiguration() {
  console.log(chalk.cyan('\n📝 Configuration\n'));

  const existingEnv = existsSync(ENV_FILE)
    ? readFileSync(ENV_FILE, 'utf-8')
        .split('\n')
        .filter(line => line && !line.startsWith('#'))
        .reduce((acc, line) => {
          const [key, ...valueParts] = line.split('=');
          acc[key.trim()] = valueParts.join('=').trim();
          return acc;
        }, {})
    : {};

  const answers = await inquirer.prompt([
    {
      type: 'number',
      name: 'port',
      message: 'Server port:',
      default: existingEnv.FZDASH_PORT || 3847,
      validate: (input) => input > 0 && input < 65536 || 'Port must be between 1 and 65535'
    },
    {
      type: 'input',
      name: 'host',
      message: 'Server host (0.0.0.0 for remote access):',
      default: existingEnv.FZDASH_HOST || '0.0.0.0'
    },
    {
      type: 'input',
      name: 'qdrantUrl',
      message: 'Qdrant URL:',
      default: existingEnv.QDRANT_URL || 'http://localhost:6363'
    },
    {
      type: 'input',
      name: 'qdrantApiKey',
      message: 'Qdrant API Key (optional):',
      default: existingEnv.QDRANT_API_KEY || ''
    },
    {
      type: 'input',
      name: 'githubToken',
      message: 'GitHub Personal Access Token (optional):',
      default: existingEnv.GITHUB_TOKEN || ''
    },
    {
      type: 'input',
      name: 'githubOwner',
      message: 'GitHub repository owner (optional):',
      default: existingEnv.GITHUB_OWNER || ''
    },
    {
      type: 'input',
      name: 'githubRepo',
      message: 'GitHub repository name (optional):',
      default: existingEnv.GITHUB_REPO || ''
    },
    {
      type: 'number',
      name: 'maxIterations',
      message: 'Claude Code max iterations (Ralph-Wiggum):',
      default: parseInt(existingEnv.CLAUDE_MAX_ITERATIONS) || 10,
      validate: (input) => input > 0 || 'Must be greater than 0'
    },
    {
      type: 'confirm',
      name: 'installRalph',
      message: 'Install ralph-wiggum plugin now?',
      default: true,
      when: () => !existsSync(join(process.env.HOME || process.env.USERPROFILE, '.config', 'claude-code', 'plugins', 'ralph-wiggum'))
    }
  ]);

  return answers;
}

function writeEnvFile(config) {
  const spinner = ora('Writing configuration...').start();

  try {
    const envContent = `# FZDash-ClaudeCode Configuration
# Generated by setup.js on ${new Date().toISOString()}

# Server
FZDASH_PORT=${config.port}
FZDASH_HOST=${config.host}

# Qdrant
QDRANT_URL=${config.qdrantUrl}
QDRANT_API_KEY=${config.qdrantApiKey}
QDRANT_COLLECTIONS=fazai_personality,fazai_memory,fazai_learning,fazai_kb,fazai_source

# GitHub
GITHUB_TOKEN=${config.githubToken}
GITHUB_OWNER=${config.githubOwner}
GITHUB_REPO=${config.githubRepo}

# Claude Code
CLAUDE_CODE_PATH=claude
CLAUDE_DEFAULT_MODEL=claude-sonnet-4-5-20250929
CLAUDE_MAX_ITERATIONS=${config.maxIterations}
CLAUDE_SKIP_PERMISSIONS=false

# Terminal
TERMINAL_SHELL=
TERMINAL_MAX_SESSIONS=10
TERMINAL_IDLE_TIMEOUT=3600000

# File Watcher
FILE_WATCHER_IGNORED=node_modules,dist,.git,*.log,*.tmp
FILE_WATCHER_MAX_DEPTH=5

# Development
DEBUG=false
VERBOSE=false
LOG_FILE=./fzdash.log
`;

    writeFileSync(ENV_FILE, envContent);
    spinner.succeed('Configuration saved to .env');
  } catch (error) {
    spinner.fail('Failed to write configuration');
    throw error;
  }
}

async function installRalphPlugin() {
  const spinner = ora('Installing ralph-wiggum plugin...').start();

  try {
    execSync('npm run install:ralph', {
      cwd: PROJECT_ROOT,
      stdio: 'pipe'
    });
    spinner.succeed('Ralph-Wiggum plugin installed');
  } catch (error) {
    spinner.fail('Failed to install ralph-wiggum plugin');
    console.log(chalk.yellow('\nYou can install it manually later with:'));
    console.log(chalk.gray('  npm run install:ralph\n'));
  }
}

async function buildProject() {
  console.log(chalk.cyan('\n🔨 Building project...\n'));

  const spinner = ora('Building client and server...').start();

  try {
    execSync('npm run build', {
      cwd: PROJECT_ROOT,
      stdio: 'inherit'
    });
    spinner.succeed('Build completed');
    return true;
  } catch (error) {
    spinner.fail('Build failed');
    console.log(chalk.yellow('\nYou can build manually later with:'));
    console.log(chalk.gray('  npm run build\n'));
    return false;
  }
}

async function main() {
  console.log(chalk.cyan('\n╔════════════════════════════════════════════════════════════╗'));
  console.log(chalk.cyan('║') + chalk.white('  FZDash-ClaudeCode Setup Wizard                            ') + chalk.cyan('║'));
  console.log(chalk.cyan('║') + chalk.gray('  Dashboard for Claude Code + FazAI-NG Integration           ') + chalk.cyan('║'));
  console.log(chalk.cyan('╚════════════════════════════════════════════════════════════╝\n'));

  // Check dependencies
  checkDependencies();

  // Check optional services
  const qdrantAvailable = checkQdrant();
  const claudeCodeAvailable = checkClaudeCode();

  if (!qdrantAvailable) {
    console.log(chalk.yellow('\n⚠ Qdrant is not running or not accessible'));
    console.log(chalk.gray('  The dashboard will work, but Qdrant features will be unavailable'));
    console.log(chalk.gray('  Start Qdrant on port 6363 to enable ECOA collections\n'));
  }

  if (!claudeCodeAvailable) {
    console.log(chalk.yellow('\n⚠ Claude Code is not installed'));
    console.log(chalk.gray('  Install with: npm install -g @anthropic-ai/claude-code\n'));
  }

  // Configuration prompts
  const config = await promptConfiguration();

  // Write .env file
  writeEnvFile(config);

  // Install ralph-wiggum if requested
  if (config.installRalph) {
    await installRalphPlugin();
  }

  // Ask about building
  const { shouldBuild } = await inquirer.prompt([
    {
      type: 'confirm',
      name: 'shouldBuild',
      message: 'Build the project now?',
      default: true
    }
  ]);

  if (shouldBuild) {
    await buildProject();
  }

  // Success message
  console.log(chalk.green('\n✓ Setup completed successfully!\n'));
  console.log(chalk.white('Next steps:\n'));

  if (!shouldBuild) {
    console.log(chalk.gray('  1. Build the project:'));
    console.log(chalk.cyan('     npm run build\n'));
  }

  console.log(chalk.gray('  ' + (shouldBuild ? '1' : '2') + '. Start the dashboard:'));
  console.log(chalk.cyan('     npm run dev') + chalk.gray('     # Development mode'));
  console.log(chalk.cyan('     npm start') + chalk.gray('       # Production mode\n'));

  console.log(chalk.gray('  ' + (shouldBuild ? '2' : '3') + '. Open in browser:'));
  console.log(chalk.cyan(`     http://${config.host === '0.0.0.0' ? 'localhost' : config.host}:${config.port}\n`));

  if (config.host === '0.0.0.0') {
    console.log(chalk.gray('  💡 Remote access enabled! Access from other devices at:'));
    console.log(chalk.cyan('     http://<your-ip>:' + config.port + '\n'));
  }
}

// Run setup
main().catch(error => {
  console.error(chalk.red('\n✗ Setup failed:'), error.message);
  process.exit(1);
});
